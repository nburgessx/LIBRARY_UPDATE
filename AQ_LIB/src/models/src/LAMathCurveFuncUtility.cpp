/* @brief			Update the accrual frequency if it is greater than the payment frequency
* @param [in]		paymentFreq			Payment freqquency
* @return True if it is fixing in advance
*/
bool LAMathCurveFuncUtility::isFixingInAdvance(const AQLString& fixingAdvanceOrArrears)
{
    bool fixingInAdvance = true;
    if ( fixingAdvanceOrArrears.size() > 0 )
        {
            AQLString fixingAdOrAr( fixingAdvanceOrArrears );
            fixingAdOrAr.toLower();

            if ( fixingAdOrAr != "adv"
                    && fixingAdOrAr != "advance"
                    && fixingAdOrAr != "arr"
                    && fixingAdOrAr != "arrears" )
            {
                throw AQLCoreInvalidData( "#Error: Invalid Input, the 'fixingAdvanceOrArrears' parameter must be set to 'advance', 'arrears', 'adv', 'arr' or left blank.", __FILE__, __LINE__ );
            }
            else if ( fixingAdOrAr == "arrears" || fixingAdOrAr == "arr" )
            {
                fixingInAdvance = false;
            }
     }
	return fixingInAdvance;
}

// Update the accrual frequency if it is greater than the payment frequency
// *** Duplicate OF LACurveForwardRateHelpers.cpp UpdateAccrualFrequency ***
static void updateAccrualFrequency(AQLString& accrualFreq, const AQLString& paymentFreq, bool fixingInAdvance=true)
{
	if ( accrualFreq == paymentFreq ) return;

	double accrualFreqInMonths = LAMathDateCalculations::getPeriodFrequencyInMonths(accrualFreq);
	if (paymentFreq != AQLString())
	{
		double paymentFreqInMonths = LAMathDateCalculations::getPeriodFrequencyInMonths(paymentFreq);
		
		// For instance, if paymentFrequency is Semi-Annual, and accrualFrequency is Annual, use Semi-Annual as the accrualFrequency 
		if (accrualFreqInMonths > paymentFreqInMonths)
		{
            if (!fixingInAdvance)
            {
                throw AQLCoreInvalidData( "#Error: Unable to fix in Arrears, since floating payments cannot be made before their fixing dates.", __FILE__, __LINE__ );
            }
			accrualFreq = paymentFreq;
		}
	}
}

/* @brief			Add entries to to payment dates to match the size of the accrual dates
* @param [in]		accrualDates Accrual dates
* @param [in]		paymentDates Payment dates
* @return payment dates with the same size of accrual dates
*/
static DateVector updatePaymentDates(const DateVector& accrualDates, const DateVector& paymentDates)
{
	size_t accrualSize = accrualDates.size();
	size_t paymentSize = paymentDates.size();
    if (accrualSize == 0)
	{
        throw AQLCoreInvalidData( "#Error: The size of Accrual Dates cannot be empty.", __FILE__, __LINE__ );
	}
    if (paymentSize == 0)
	{
        throw AQLCoreInvalidData( "#Error: The size of Payment Dates cannot be empty.", __FILE__, __LINE__ );
	}

	DateVector result;
	if (accrualSize == paymentSize)
	{
		result = paymentDates;
	}
	else if (accrualSize > paymentSize)
	{
		//add duplicate entries to paymentDates to match the size of accrualDates, starting from index 1
		
		// First payment date is artificial so it is always added
		result.push_back(paymentDates[0]);

		size_t accrualIndex = 1;
		size_t paymentIndex = 1;
		while (accrualIndex < accrualSize && paymentIndex < paymentSize)
		{
			AQLDate accrualDt = accrualDates[accrualIndex];
			AQLDate paymentDt = paymentDates[paymentIndex];

			if(accrualDt <= paymentDt)
			{
				result.push_back(paymentDt);
				accrualIndex++;
			}
			else 
			{
				paymentIndex++;
			}
		}
	}

    if ( accrualDates.size() != result.size())
	{
        throw AQLCoreInvalidData( "#Error: The size of Accrual Dates and Payment Dates must be the same.", __FILE__, __LINE__ );
	}

	return result;

}

