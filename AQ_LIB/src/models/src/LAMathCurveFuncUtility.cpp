bool isNumber( const AQLString& inputString )
{
    std::string s = inputString.getCString();
    std::string::const_iterator it = s.begin();
    // interate over and check if every charater is numeric
    while ( it != s.end() && isdigit( *it ) )
    {
        ++it;
    }
    return !s.empty() && it == s.end();
}


double
LAMathCurveFuncUtility::compound(AQLDataInstance* dataInstance,
                           const AQLString& curveID,
                           const AQLString& forecastCurveName,
                           const AQLDate& start_date,
                           const AQLDate& end_date,
                           const double spread,
                           const AQLString& frequency_,
                           const bool is_start_roll,
                           const AQLString& roll_convention_,
                           const AQLString& calendar_,
                           const AQLString& sliding_rule_,
                           const AQLString& day_count_,
                           const AQLString& interpolation_,
                           const AQLString& compound_type_,
                           const AQLDate* first_odd,
                           const AQLDate* last_odd,
						   const bool usePDay)
{
    AQLString frequency = frequency_; frequency.toUpper();
    AQLString roll_convention = roll_convention_; roll_convention.toUpper();
    AQLString calendar = calendar_; calendar.toUpper();
    AQLString sliding_rule = sliding_rule_; sliding_rule.toUpper();
    AQLString day_count = day_count_; day_count.toUpper();
    AQLString interpolation = interpolation_; interpolation.toUpper();
    AQLString compound_type_str = compound_type_; compound_type_str.toUpper();
    
    LAMathCurveFuncUtility::COMPOUND_TYPE compound_type;
    if(compound_type_str=="NORMAL") compound_type = LAMathCurveFuncUtility::COMPOUND_NORMAL;
    else if(compound_type_str=="FLAT") compound_type = LAMathCurveFuncUtility::COMPOUND_FLAT;
    else if(compound_type_str=="SIMPLE") compound_type = LAMathCurveFuncUtility::COMPOUND_SIMPLE;
    else if(compound_type_str=="AVERAGE") compound_type = LAMathCurveFuncUtility::AVERAGE;
    else{
        AQLString msg;
        msg += "Unknown compound type:";
        msg += compound_type_;
        throw AQLCoreInvalidData(msg.getCString(), __FILE__, __LINE__);
    }

	
    AQLPriceDataCalendar data_cal; data_cal.convertFromString(calendar);
    AQLPriceDataSlidingRule data_sr; data_sr.convertFromString(sliding_rule);

    DateVector payment_dates;

	// The rollDay(roll_convention param here) can be either string, NORMAL,STARTDATE,ENDDATE,LUNAR,EOM,IMM; or numeric type
	// If the rollDay is numeric type, pass it to Pday; otherwise, pass it to rollConv
	AQLString* rollConv = &roll_convention;	
	int* pDay = NULL;
	int tempDay=0;
	if (usePDay) 
	{
		if (isNumber(roll_convention)) 
		{
			tempDay =  roll_convention.getIntValue();
			pDay = &tempDay;
			rollConv = NULL;
		}
	}

    LAMathDateCalculations::generateSchedule(
        start_date,
        end_date,
        frequency,
        true, 
        first_odd,
        last_odd,
        pDay, 
        payment_dates,
        &data_sr,
        &data_cal,
        is_start_roll,
        rollConv);

    const size_t n = payment_dates.size();
    DateVector start_dates(n), end_dates(n);
    start_dates[0] = start_date;
    end_dates[0] = payment_dates[0];
    for(size_t i = 1; i < n; i++){
        start_dates[i] = payment_dates[i-1];
        end_dates[i] = payment_dates[i];
    }



    const AQLString freq = SIMPLE;

	const LAMathYieldCurve& yc = LAMathCurveFuncUtility::getYieldCurveForCurveID(dataInstance,curveID);
	const AQLObject& yieldData = yc.getYieldData().get().get();
	AQLString suffix;
	if (forecastCurveName != STD)
	{
		suffix = "_" + forecastCurveName;
	}
	const AQLDataHolder* dh = &(yieldData.getData(CALIBRATION_DATA_FWDTERMSMATRIX + suffix, NOCHECK));
	const bool is_fwd_inter = dh->isDefined() && !dh->isNull();

    DoubleArray rates = LAMathCurveFuncUtility::getMultiForwardRate(start_dates,
                                                                  end_dates,
                                                                  dataInstance,
                                                                  curveID,
                                                                  freq,
                                                                  day_count,
                                                                  sliding_rule,
                                                                  calendar,
                                                                  interpolation,
                                                                  forecastCurveName,
																  is_fwd_inter);


    AQLPriceDataDayCount dc; dc.convertFromString(day_count);
    DoubleVector x(3*n);
    copy(rates.begin(), rates.end(), x.begin());
    for(size_t i = 0; i < n; i++){
        x[n+i]     = dc.getTerm(start_dates[i], end_dates[i]);
        x[n*2 + i] = spread;
    }
	std::shared_ptr<LACompoundMethod> method;
    switch(compound_type){
        case COMPOUND_NORMAL:
            {
                method.reset(new LACompoundMethod7());
                break;
            }
        case COMPOUND_FLAT:
            {
                method.reset(new LACompoundMethod8());
                break;
            }
        case COMPOUND_SIMPLE:
            {
                method.reset(new LACompoundMethod9());
                x.push_back(dc.getTerm(start_date, end_date));
                break;
            }
        case AVERAGE:
            {
                method.reset(new LACompoundMethod10());
                break;
            }
    }

    return (*method)(x);
};

