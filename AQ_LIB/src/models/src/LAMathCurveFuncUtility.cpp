/* @brief			helper method that validates and generates accrual start and end dates from a single combined vector of accrual dates
*  @param [out]		accrualStartDates		    Accrual Start Dates
*  @param [out]		accrualEndDates		        Accrual End Dates
*  @param [in]		combinedAccrualDates        Combined Accrual Dates
*/
void LAMathCurveFuncUtility::validateAndGenerateAccrualStartAndEndDates(DateVector& accrualStartDates,
																	DateVector& accrualEndDates,
																	const DateVector& combinedAccrualDates)
{
    size_t nCombinedAccrualDates = combinedAccrualDates.size() - 1;

    if ( nCombinedAccrualDates < 1 )
    {
        throw LACoreInvalidData( "#Error: Swap Accrual Dates Error, cannot have an accrual start date and no accrual end date", __FILE__, __LINE__ );
    }

    accrualStartDates.clear();
    accrualEndDates.clear();

	LADate curDate;
    for ( size_t i = 0; i <= nCombinedAccrualDates ; ++i )
    {
		curDate = combinedAccrualDates[i]; 
 		if (i == 0)
		{
		    // The first date is used for the start date only
			accrualStartDates.push_back(curDate);
		}
		else if (i == nCombinedAccrualDates)
		{
			// The last date is used for the end date only
			accrualEndDates.push_back(curDate);
		}
		else
		{
			// populate both
			accrualStartDates.push_back(curDate);
			accrualEndDates.push_back(curDate);
		}
    }

}

/* @brief Function to get the Accrual Schedule and Payment Schedule for fixed/float leg
*
*  @param [out]   accrualDates               ( placeholder for the result )
*  @param [out]   paymentDates               ( placeholder for the result )
*  @param [in]    effectiveDate              The swap start or effective date
*  @param [in]    maturityDate               The swap end or maturity date
*  @param [in]    accrualFrequency           Accrual frequency
*  @param [in]    acrualBusDayAdjustment     Accrual business day adjustment, Modified_Following, Following, Preceding, Modified_Preceding or No_Change
*  @param [in]    accrualCalendar            Accrual calendar
*  @param [in]    paymentFreq                Payment frequency
*  @param [in]    paymentBusDayAdjustment    Payment business day adjustment, Modified_Following, Following, Preceding, Modified_Preceding or No_Change
*  @param [in]    paymentCalendar            Payment calendar
*  @param [in]    paymentLag                 Payment lag
*  @param [in]    stubType                   Stub type; ShortStart, ShortEnd, LongStart, LongEnd
*  @param [in]    firstStubDate              First stub date
*  @param [in]    lastStubDate               Last stub date
*  @param [in]    rollDay                    Roll day, an integer representing the day of the month
*  @param [in]    isStartRoll                Are coupons rolling from the start day i.e. ShortEnd stub? True or False          
*  @param [in]    isEomRoll                  Are coupons rolling on month end? True or False
*  @param [in]    rollConvention             Roll convention: IMM, EOM, Start, End or NULL
*  @param [in]	  fixingAdvanceOrArrears	 Flag to indicate the fixing is advance or arrears
*  @param [in]    removeExtraPaymentDay		 True to remove the extra payment date at the front. Default to False for backward compatibility, as all the core functions expect payment dates having the same size as accrual days
*/
void 
LAMathCurveFuncUtility::generateAccrualAndPaymentSchedule(DateVector& accrualDates,
												DateVector&     paymentDates,
												LADate			effectiveDate,
												LADate          maturityDate,
												LAString        accrualFrequency,
												LAString        accrualBusinessDayAdjustment,
												LAString        accrualCalendar,
												LAString		paymentFrequency,
												LAString        paymentBusinessDayAdjustment,
												LAString        paymentCalendar,
												LAString        paymentLag,
												LAString*       stubType,
												LADate*         firstStubDate,
												LADate*         lastStubDate,
												int*            rollDay,
												bool            isStartRoll,
												bool            isEomRoll,
												LAString*       rollConvention,
												const LAString& fixingAdvanceOrArrears,
												bool			removeExtraPaymentDay)

{

	LAString endOfMonthRollConv("EOM");
	LAString* rollConv = rollConvention;
	if (isEomRoll && isLastBusinessDay( effectiveDate, accrualCalendar ) )
	{
		rollConv = &endOfMonthRollConv;
	}

    // Accrual Dates
    ///////////////////////////
	bool fixingInAdvance = isFixingInAdvance(fixingAdvanceOrArrears);
	updateAccrualFrequency(accrualFrequency, paymentFrequency, fixingInAdvance);

	accrualDates = LAMathDateUtilities::generateSchedule( effectiveDate, 
														  maturityDate,      
														  accrualFrequency,
														  accrualBusinessDayAdjustment,  
														  accrualCalendar,
														  firstStubDate,                
														  lastStubDate,                   
														  rollDay,
														  isStartRoll,
														  rollConv,
														  stubType );

    // Payment Dates
    ///////////////////////////
	LAString paymentFreq = (paymentFrequency==LAString()) ? accrualFrequency : paymentFrequency;
	DateVector paymentDatesNoLag = LAMathDateUtilities::generateSchedule(effectiveDate, 
													maturityDate,      
													paymentFreq,
													paymentBusinessDayAdjustment,  
													paymentCalendar,
													firstStubDate,                
													lastStubDate,                   
													rollDay,
													isStartRoll,
													rollConv,
													stubType );

	DateVector tempPaymentDates;
	upper(paymentLag);
	if (paymentLag.size()!= 0 && paymentLag != "0D")
	{
		// Payment Sliding Rule or Business Day Adjustment
		upper( paymentBusinessDayAdjustment );
		LAPriceDataSlidingRule slidingRule;
		slidingRule.convertFromString( paymentBusinessDayAdjustment );

		upper( paymentCalendar );
		LAPriceDataCalendar cal;
		cal.convertFromString( paymentCalendar );

		// Generate Payment Dates
		bool doNotAddMinusSignToTerm    = true;     // AKA: isAfterFlag - This controls if the lag is a positive or negative lag
		//Note: The paymentDates should start from the second of datesNoLag only, but the core code expects/handle the extra date, so need to leave it as it is now
		tempPaymentDates = LAMathDateUtilities::calcDatesWithLag(paymentDatesNoLag,
																	paymentLag,
																	slidingRule,
																	& cal,
																	doNotAddMinusSignToTerm, // isAfter = True,
																	nullptr );   // RollConvention: applies to accrual dates only
	}
	else
	{
		tempPaymentDates =  paymentDatesNoLag;
	}

	paymentDates = updatePaymentDates(accrualDates, tempPaymentDates);

	if (removeExtraPaymentDay) 
	{
		//remove the first artifcial day
		paymentDates.erase(paymentDates.begin());
	}


}


/*      @brief Function to get the floag leg Fixing Schedule
*
*      @param [in]  accrualDates					The swap leg accrual dates
*      @param [in]  fixingBusinessDayAdjustment     Floating fixing business day adjustment, Modified_Following, Following, Preceding, Modified_Preceding or No_Change
*      @param [in]  fixingCalendar					Floating fixing calendar 
*      @param [in]  fixingLag						Float fixing lag
*	   @param [in]	fixingAdvanceOrArrears			Flag to indicate the fixing is advance or arrears
*      @param [in]  removeExtraFixingDay			True to remove the extra fixing date. Default to False for backward compatibility, as all the core functions expect fixing dates having the same size as accrual days
*      @Return	fixingDates
*/
DateVector LAMathCurveFuncUtility::getFixingSchedule(const DateVector& accrualDates, 
														LAString  fixingBusinessDayAdjustment,
														LAString  fixingCalendar,
														LAString  fixingLag,
														const LAString& fixingAdvanceOrArrears,
														bool removeExtraFixingDay)
{
	// Generate Fixing Dates

	DateVector datesToUseForFixing;
	if (removeExtraFixingDay) 
	{
		DateVector accrualStartDates;
		DateVector accrualEndDates;
		validateAndGenerateAccrualStartAndEndDates( accrualStartDates, accrualEndDates, accrualDates);
		bool fixingInAdvance = isFixingInAdvance(fixingAdvanceOrArrears);
		datesToUseForFixing = fixingInAdvance? accrualStartDates : accrualEndDates;
	}
	else 
	{
		//keep backward compatibility
		datesToUseForFixing = accrualDates;
	}

	LAPriceDataSlidingRule fixingSlidingRule;
	upper(fixingBusinessDayAdjustment);
	fixingSlidingRule.convertFromString( fixingBusinessDayAdjustment ); // Float Leg Fixing Roll Convention = "PRECEDING"

    LAPriceDataCalendar fixingCal;
    upper( fixingCalendar );
    fixingCal.convertFromString( fixingCalendar );

	const bool addMinusSignToTerm = false;
	DateVector fixingDates = LAMathDateUtilities::calcDatesWithLag( datesToUseForFixing,
                                                         fixingLag,
                                                         fixingSlidingRule,
                                                         & fixingCal,
                                                         addMinusSignToTerm,    // isAfter = False
                                                         nullptr );      // This RollConv = Start, End, IMM, EOM or NULL

	return fixingDates;
}


