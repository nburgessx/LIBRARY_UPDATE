double 
LAMathCurveFuncUtility::getParRate(DateVector& datevec, AQLDataInstance* dataInstance, const AQLString& curveid, 
								 AQLString daycount, AQLString interpolation, AQLString foreCurveName, AQLString dfCurveName, bool isFWDInter)
{
	upper(daycount);
	upper(interpolation);
	const AQLDataDate& atr = dynamic_cast<const AQLDataDate& >(dataInstance->getObjectPool().getObject(curveid,ENCHKTYPE_ISDEFINED).get().getData(CALIBRATION_DATA_ASOFDATE,ISNOTNULL).get());
	const AQLDate asofdate = atr.get();
	if(asofdate > datevec[0])
		throw AQLCoreInvalidData(" fromdate < asofdate is not supported",__FILE__,__LINE__);  
	
	int N = datevec.size()-1;
	for(int i=1;i<N;i++)
	{
		if(datevec[i-1] >= datevec[i])
			throw AQLCoreInvalidData("Wrong input of DateVector ",__FILE__,__LINE__);
	}
	LAMathYieldCurve& yc = getYieldCurveForCurveID(dataInstance,curveid);
	AQLString inter =  AQLCoreComponentManager::getInterpolation(interpolation);
	AQLString dc = AQLCoreComponentManager::getDayCount(daycount);
	yc.setInterpolation(inter);
	yc.getDayCount().setDayCount(dc);
	
	setCalendarForCurveID(yc,"");
	yc.getSlidingRule().convertFromString(NO_CH);

	if (isFWDInter && !setUpForwardDayCount(dataInstance, curveid, foreCurveName, yc))
	{
		throw AQLCoreInvalidData("Forward interpolation failed. Check whether the forward rate was generated by LAMathYieldCurvePro !!",__FILE__,__LINE__);
	}
	
	double ret = yc.getParRate(datevec, datevec, foreCurveName, dfCurveName, isFWDInter);
	return ret;
}


/*
* @brief	Calculate stub rate of a defined stub period
*/
double LAMathCurveFuncUtility::getStubRate( AQLDataInstance* dataInstance,
									const DateVector& fixingDates,
									const AQLStringVector& curveNames,
									const AQLStringVector& curveTenors,
									const DoubleVector& tenorCurveFixings,
									const AQLString& curveid,									
									const AQLString& stubType,
									const AQLString& interpolation,
									const AQLString& dateCount,
									const AQLString& calendar,
									const AQLString& busDayAdj,
									bool  useNearbyCurve,									
									bool  isFwdInter,
									bool  useFwdData,
									const AQLString& toleranceTenor,
									const AQLString& useCurveName)
{
	AQLString STUBTYPE( stubType );
	upper( STUBTYPE );

    AQLString INTERPOLATION( interpolation );
	upper( INTERPOLATION );

	AQLString DATECOUNT( dateCount );
    upper( DATECOUNT );

	AQLString CALENDAR( calendar );
    upper( CALENDAR );

    AQLString BUSDAYADJ( busDayAdj );
	upper( BUSDAYADJ );

    //
    // Validate inputs
    //
	size_t nFixingDates = fixingDates.size();
	for( size_t i = 1; i < nFixingDates; i++ )
	{
		if( fixingDates[i-1] >= fixingDates[i] )
		{
            throw AQLCoreInvalidData("#Error: Invalid Fixing Date(s).",__FILE__,__LINE__);
		}
	}
	
	size_t nCurveNames = curveNames.size();
	size_t nCurveTenors = curveNames.size();
	size_t nFixings = tenorCurveFixings.size();
	if (nCurveNames != nCurveTenors)
	{
		throw AQLCoreInvalidData("#Error: The number of curve names must equal the number of curve tenors",__FILE__,__LINE__);
	}

	if (nFixings != 0 && nFixings != nCurveNames)
	{
		throw AQLCoreInvalidData("#Error: If past fixings are provided, they must be provided for each curve name",__FILE__,__LINE__);
	}

	bool useGivenFixings = nFixings == 0 ? false : true;

	// Retrieve yield curve through curveid
	LAMathYieldCurve& yc = getYieldCurveForCurveID(dataInstance,curveid);
	
	// Set essential curve parameters
	AQLString inter =  AQLCoreComponentManager::getInterpolation( INTERPOLATION );
    yc.setInterpolation(inter);

	AQLString dc = AQLCoreComponentManager::getDayCount( DATECOUNT );
    yc.getDayCount().setDayCount( dc ); 
	
	setCalendarForCurveID( yc, "" );
	yc.getSlidingRule().convertFromString( NO_CH );

	double stubRate = yc.getStubRate(fixingDates,
									curveNames,
									curveTenors,
									tenorCurveFixings,									
									curveid,									
									STUBTYPE,           // Uppercase
									DATECOUNT,          // Uppercase
									CALENDAR,           // Uppercase
									BUSDAYADJ,          // Uppercase
									useNearbyCurve,
									useGivenFixings,
									isFwdInter,
									useFwdData,
									toleranceTenor,
									useCurveName);

	return stubRate;
}



