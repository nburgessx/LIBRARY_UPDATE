double 
LAMathCurveFuncUtility::getParRate(DateVector& datevec, LADataInstance* dataInstance, const LAString& curveid, 
								 LAString daycount, LAString interpolation, LAString foreCurveName, LAString dfCurveName, bool isFWDInter)
{
	upper(daycount);
	upper(interpolation);
	const LADataDate& atr = dynamic_cast<const LADataDate& >(dataInstance->getObjectPool().getObject(curveid,ENCHKTYPE_ISDEFINED).get().getData(CALIBRATION_DATA_ASOFDATE,ISNOTNULL).get());
	const LADate asofdate = atr.get();
	if(asofdate > datevec[0])
		throw LACoreInvalidData(" fromdate < asofdate is not supported",__FILE__,__LINE__);  
	
	int N = datevec.size()-1;
	for(int i=1;i<N;i++)
	{
		if(datevec[i-1] >= datevec[i])
			throw LACoreInvalidData("Wrong input of DateVector ",__FILE__,__LINE__);
	}
	LAMathYieldCurve& yc = getYieldCurveForCurveID(dataInstance,curveid);
	LAString inter =  LACoreComponentManager::getInterpolation(interpolation);
	LAString dc = LACoreComponentManager::getDayCount(daycount);
	yc.setInterpolation(inter);
	yc.getDayCount().setDayCount(dc);
	
	setCalendarForCurveID(yc,"");
	yc.getSlidingRule().convertFromString(NO_CH);

	if (isFWDInter && !setUpForwardDayCount(dataInstance, curveid, foreCurveName, yc))
	{
		throw LACoreInvalidData("Forward interpolation failed. Check whether the forward rate was generated by LAMathYieldCurvePro !!",__FILE__,__LINE__);
	}
	
	double ret = yc.getParRate(datevec, datevec, foreCurveName, dfCurveName, isFWDInter);
	return ret;
}


/*
* @brief	Calculate stub rate of a defined stub period
*/
double LAMathCurveFuncUtility::getStubRate( LADataInstance* dataInstance,
									const DateVector& fixingDates,
									const LAStringVector& curveNames,
									const LAStringVector& curveTenors,
									const DoubleVector& tenorCurveFixings,
									const LAString& curveid,									
									const LAString& stubType,
									const LAString& interpolation,
									const LAString& dateCount,
									const LAString& calendar,
									const LAString& busDayAdj,
									bool  useNearbyCurve,									
									bool  isFwdInter,
									bool  useFwdData,
									const LAString& toleranceTenor,
									const LAString& useCurveName)
{
	LAString STUBTYPE( stubType );
	upper( STUBTYPE );

    LAString INTERPOLATION( interpolation );
	upper( INTERPOLATION );

	LAString DATECOUNT( dateCount );
    upper( DATECOUNT );

	LAString CALENDAR( calendar );
    upper( CALENDAR );

    LAString BUSDAYADJ( busDayAdj );
	upper( BUSDAYADJ );

    //
    // Validate inputs
    //
	size_t nFixingDates = fixingDates.size();
	for( size_t i = 1; i < nFixingDates; i++ )
	{
		if( fixingDates[i-1] >= fixingDates[i] )
		{
            throw LACoreInvalidData("#Error: Invalid Fixing Date(s).",__FILE__,__LINE__);
		}
	}
	
	size_t nCurveNames = curveNames.size();
	size_t nCurveTenors = curveNames.size();
	size_t nFixings = tenorCurveFixings.size();
	if (nCurveNames != nCurveTenors)
	{
		throw LACoreInvalidData("#Error: The number of curve names must equal the number of curve tenors",__FILE__,__LINE__);
	}

	if (nFixings != 0 && nFixings != nCurveNames)
	{
		throw LACoreInvalidData("#Error: If past fixings are provided, they must be provided for each curve name",__FILE__,__LINE__);
	}

	bool useGivenFixings = nFixings == 0 ? false : true;

	// Retrieve yield curve through curveid
	LAMathYieldCurve& yc = getYieldCurveForCurveID(dataInstance,curveid);
	
	// Set essential curve parameters
	LAString inter =  LACoreComponentManager::getInterpolation( INTERPOLATION );
    yc.setInterpolation(inter);

	LAString dc = LACoreComponentManager::getDayCount( DATECOUNT );
    yc.getDayCount().setDayCount( dc ); 
	
	setCalendarForCurveID( yc, "" );
	yc.getSlidingRule().convertFromString( NO_CH );

	double stubRate = yc.getStubRate(fixingDates,
									curveNames,
									curveTenors,
									tenorCurveFixings,									
									curveid,									
									STUBTYPE,           // Uppercase
									DATECOUNT,          // Uppercase
									CALENDAR,           // Uppercase
									BUSDAYADJ,          // Uppercase
									useNearbyCurve,
									useGivenFixings,
									isFwdInter,
									useFwdData,
									toleranceTenor,
									useCurveName);

	return stubRate;
}



